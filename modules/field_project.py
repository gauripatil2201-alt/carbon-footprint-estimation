import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt
import streamlit as st

df = pd.read_csv("data/FP_data2.csv")

def show_fig(fig):
    fig.tight_layout()
    st.pyplot(fig, use_container_width=False)
    plt.close(fig)

def demographics():
    household_count = df["Household Type"].value_counts()
    fig, ax = plt.subplots(figsize=(4, 4))
    ax.pie(household_count, labels=household_count.index, startangle=90)
    ax.set_title("Distribution of household types")
    show_fig(fig)

    residence_count = df["Residence Type"].value_counts()
    fig, ax = plt.subplots(figsize=(4,4))
    ax.pie(residence_count, labels=residence_count.index, startangle=90)
    ax.set_title("Distribution of residence types")
    show_fig(fig)

def energy_usage():
    ele_count = df["Electricity Source"].value_counts()
    fig, ax = plt.subplots(figsize=(4, 3))
    ax.bar(ele_count.index, ele_count.values, color="skyblue")
    ax.set_xlabel("Type of Electricity")
    ax.set_ylabel("No. of households")
    ax.tick_params(axis="x", rotation=45)
    show_fig(fig)

    fuel_count = df["Cooking Fuel"].value_counts()
    fig, ax = plt.subplots(figsize=(4, 3))
    ax.bar(fuel_count.index, fuel_count.values, color="skyblue")
    ax.set_xlabel("Type of fuel used for cooking")
    ax.set_ylabel("No. of households")
    ax.tick_params(axis="x", rotation=25)
    show_fig(fig)

    categories = ["Yes", "No"]
    renewable = df["Renewable Energy Usage"].value_counts()
    efficient = df["Energy Efficient Appliances"].value_counts()

    x = np.arange(len(categories))
    width = 0.40

    fig, ax = plt.subplots(figsize=(5, 3.5))
    ax.bar(x - width/2, [renewable.get(c, 0) for c in categories],
           width, label="Renewable Energy")
    ax.bar(x + width/2, [efficient.get(c, 0) for c in categories],
           width, label="Energy-Efficient Appliances")
    ax.set_title("Adoption of Renewable Energy vs. Energy-Efficient Appliances")
    ax.set_xticks(x)
    ax.set_xticklabels(categories)
    ax.set_ylabel("Number of Households")
    ax.legend()
    show_fig(fig)

    df["Appliances Used"] = df["Appliances Used"].str.strip().str.lower()
    app_split = df["Appliances Used"].str.get_dummies(sep=",")
    df_app = pd.concat([df["Household Type"], app_split], axis=1)
    app_usage = df_app.groupby("Household Type").sum()

    fig, ax = plt.subplots(figsize=(5, 3.5))
    sns.heatmap(app_usage, annot=True, cmap="YlGnBu", fmt="d", ax=ax)
    ax.set_xlabel("Appliances")
    ax.set_ylabel("Household Type")
    ax.set_title("Usage of electrical Appliances by Household Type")
    ax.tick_params(axis="x", rotation=90)
    show_fig(fig)

def waste():
    
    waste_separation_count = df["Waste Separation"].value_counts()
    fig, ax = plt.subplots(figsize=(3, 3))
    ax.pie(waste_separation_count, labels=waste_separation_count.index, startangle=90)
    ax.set_title("Separation of Recyclable waste")
    show_fig(fig)

    df["Waste Types"] = df["Waste Types"].str.strip().str.lower()
    waste_split = df["Waste Types"].str.get_dummies(sep=",")
    df_waste = pd.concat([df["Household Type"], waste_split], axis=1)
    waste_household = df_waste.groupby("Household Type").sum().T
    ax = waste_household.plot(kind="bar", stacked=True, figsize=(5, 4))
    fig = ax.get_figure()
    ax.set_title("Types of Waste Generated by Household Type")
    ax.set_ylabel("Number of Households")
    ax.set_xlabel("Type of Waste")
    ax.legend(title="Type of Household")
    ax.tick_params(axis="x", rotation=90)
    show_fig(fig)

