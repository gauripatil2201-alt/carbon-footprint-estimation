def awareness():
    order=["1- Not aware","2- Slightly aware","3- Moderately aware","4- Very aware","5- Extremely aware"]
    aware_count = df["Carbon Footprint Awareness"].value_counts().reindex(order)
    fig, ax = plt.subplots(figsize=(4, 3))
    ax.bar(aware_count.index, aware_count.values, color="green")
    ax.set_xlabel("Awareness Level")
    ax.set_ylabel("No. of households")
    ax.set_title("Awareness of Carbon footprint")
    ax.tick_params(axis="x", rotation=25)
    show_fig(fig)

    order=["1- Not Important","2- Slightly Important","3- Moderately Important","4- Important"]
    imp_count = df["Importance of Carbon Reduction"].value_counts().reindex(order)
    fig, ax = plt.subplots(figsize=(4, 3))
    ax.bar(imp_count.index, imp_count.values, color="green")
    ax.set_xlabel("Importance Level")
    ax.set_ylabel("No. of households")
    ax.set_title("Importance of reducing Carbon footprint")
    ax.tick_params(axis="x", rotation=25)
    show_fig(fig)

    blf_count = df["Belief in Household Impact"].value_counts()
    fig, ax = plt.subplots(figsize=(4, 3))
    ax.pie(blf_count, labels=blf_count.index, startangle=90)
    ax.set_title("Belief in Household Impact")
    show_fig(fig)

    df["Main Carbon Contributor"] = df["Main Carbon Contributor"].str.strip().str.lower()
    contributer_split = df["Main Carbon Contributor"].str.get_dummies(sep=",")
    df_contributer = pd.concat([df["Household Type"], contributer_split], axis=1)
    contributer_household = df_contributer.groupby("Household Type").sum().T
    ax = contributer_household.plot(kind="bar", stacked=True, figsize=(5, 4))
    fig = ax.get_figure()
    ax.set_title("Main carbon contributer by Household Type")
    ax.set_ylabel("Number of Households")
    ax.set_xlabel("Carbon Contributer")
    ax.legend(title="Type of Household")
    ax.tick_params(axis="x", rotation=90)
    show_fig(fig)