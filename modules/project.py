import pandas as pd
df=pd.read_excel("data/field_project_data.xlsx")
def mapping(df):
    house_map={
            "Joint Family ":"Joint Family",
            "Nuclear Family ":"Nuclear Family",
            "Living Alone / एकट्या व्यक्तीचे कुटुंब":"Living Alone",
            "Nuclear Family": "Nuclear Family",
            "Joint Family": "Joint Family",
            "Living Alone": "Living Alone"
        }

    df["Household Type"] = df["Type of Household "].replace(house_map).str.strip().str.title()
    df.drop(columns=["Type of Household "], inplace=True)

    df["What types of waste are commonly generated by your household?"] = (
        df["What types of waste are commonly generated by your household?"].str.lower().str.replace(r"\s+", " ", regex=True).str.strip()                          
        )
    waste_map = {
            "food waste": "Food Waste",
            "paper & cardboard": "Paper & Cardboard",
            "plastic": "Plastic",
            "glass": "Glass",
            "metal": "Metal",
            "electronic waste": "Electronic Waste",
            "none of above": "None"
        }
    df["Waste Types"]=df["What types of waste are commonly generated by your household?"].replace(waste_map).str.strip().str.title()
    df.drop(columns=["What types of waste are commonly generated by your household?"],inplace=True)

    return df
df=mapping(df)
df.columns=[
    "Timestamp",
    "Email",
    "Respondant Name",
    "Residence Type",
    "Age Group",
    "Household Size",
    "Cooking Fuel",
    "Electricity Source",
    "Transportation Mode",
    "Energy Efficient Appliances",
    "Waste Separation",
    "Renewable Energy Usage",
    "Appliances Used",
    "Energy Saving Practices",
    "Energy Consumption Rating",
    "Importance of Carbon Reduction",
    "Carbon Footprint Awareness",
    "Private Vehicle Usage",
    "Packaged Food Consumption",
    "Switch Off Appliances",
    "Main Carbon Contributor",
    "Belief in Household Impact",
    "Suggested Changes",
    "Suggestions",
    "Household Type",
    "Waste Types"
]
print(df.columns)
df.to_csv("FP_data2.csv",index=False)
